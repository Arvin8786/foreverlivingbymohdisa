'use strict';
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
process.env.XDG_CACHE_HOME ||= path.join(require('node:os').tmpdir(), 'fl-image-cache');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
(async () => {
    await fs.mkdir(process.env.XDG_CACHE_HOME, { recursive: true });
    const out = path.join(root, 'assets/images'); await fs.mkdir(out, { recursive: true });
    const map = {}; let original = 0;
    for (const filename of (await fs.readdir(root)).filter(f => /\.(jpg|png)$/i.test(f)).sort()) {
        const input = await fs.readFile(path.join(root, filename)); original += input.length;
        const hash = crypto.createHash('sha256').update(input).digest('hex').slice(0, 16);
        const target = `assets/images/${hash}.webp`;
        await sharp(input).rotate().resize({ width: 960, height: 960, fit: 'inside', withoutEnlargement: true }).webp({ quality: 80 }).toFile(path.join(root, target));
        map[filename] = target;
    }
    await sharp(path.join(root, 'FL.jpg')).resize(256, 256, { fit: 'inside' }).webp({ quality: 85 }).toFile(path.join(root, 'assets/logo.webp'));
    map['FL.jpg'] = 'assets/logo.webp';
    await sharp(path.join(root, 'arvind.jpg')).resize({ width: 480, withoutEnlargement: true }).webp({ quality: 82 }).toFile(path.join(root, 'assets/owner.webp'));
    map['arvind.jpg'] = 'assets/owner.webp';
    const logo = await sharp(path.join(root, 'FL.jpg')).resize(430, 430, { fit: 'contain', background: '#fbfaf6' }).toBuffer();
    const label = Buffer.from('<svg width="1200" height="150"><text x="600" y="60" text-anchor="middle" font-family="sans-serif" font-size="32" font-weight="bold" fill="#064e3b">Forever Living by Muhd Isa</text><text x="600" y="105" text-anchor="middle" font-family="sans-serif" font-size="22" fill="#5f6e67">Explore the collection</text></svg>');
    await sharp({ create: { width: 1200, height: 630, channels: 3, background: '#fbfaf6' } }).composite([{ input: logo, top: 30, left: 385 }, { input: label, top: 470, left: 0 }]).jpeg({ quality: 82, mozjpeg: true }).toFile(path.join(root, 'assets/social.jpg'));
    await fs.writeFile(path.join(root, 'image-map.js'), '/* Generated by npm run images. Original image paths remain valid. */\nwindow.FL_IMAGE_MAP = ' + JSON.stringify(map, null, 2) + ';\n');
    const logoBytes = (await fs.stat(path.join(root, 'assets/logo.webp'))).size;
    console.log(`Optimized ${Object.keys(map).length} image aliases. Original image files retained. Logo: ${logoBytes} bytes.`);
})().catch(error => { console.error(error.message); process.exitCode = 1; });
